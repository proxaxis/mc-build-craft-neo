package com.buildcraftneo.data;

import com.buildcraftneo.BCN;
import com.mojang.serialization.Codec;
import net.fabricmc.fabric.api.attachment.v1.AttachmentRegistry;
import net.fabricmc.fabric.api.attachment.v1.AttachmentType;

public final class BCNAttachments {
    private BCNAttachments() {}

    // ---- per-player (ServerPlayer) attachments ----

    /** Faction id string: none|science|magic */
    public static final AttachmentType<String> FACTION = AttachmentRegistry.<String>builder()
            .persistent(Codec.STRING)
            .initializer(() -> Faction.NONE.id())
            .buildAndRegister(BCN.id("faction"));

    /** Job id string: none|warrior|assassin|guardian|mage|healer|archer|scientist */
    public static final AttachmentType<String> JOB = AttachmentRegistry.<String>builder()
            .persistent(Codec.STRING)
            .initializer(() -> Job.NONE.id())
            .buildAndRegister(BCN.id("job"));

    /** Wallet balance in MD (Minecraft Dollar). */
    public static final AttachmentType<Long> MD = AttachmentRegistry.<Long>builder()
            .persistent(Codec.LONG)
            .initializer(() -> 0L)
            .buildAndRegister(BCN.id("md"));

    /** Current MP (Magic Point). */
    public static final AttachmentType<Integer> MP = AttachmentRegistry.<Integer>builder()
            .persistent(Codec.INT)
            .initializer(() -> 0)
            .buildAndRegister(BCN.id("mp"));

    /** Max MP, adjusted by job. */
    public static final AttachmentType<Integer> MP_MAX = AttachmentRegistry.<Integer>builder()
            .persistent(Codec.INT)
            .initializer(() -> 100)
            .buildAndRegister(BCN.id("mp_max"));

    /** Job experience points (Player Skills-style). level = xp / 100 + 1. */
    public static final AttachmentType<Integer> XP = AttachmentRegistry.<Integer>builder()
            .persistent(Codec.INT)
            .initializer(() -> 0)
            .buildAndRegister(BCN.id("xp"));

    /** Cumulative environmental footprint generated by this player. */
    public static final AttachmentType<Double> EFP_OWN = AttachmentRegistry.<Double>builder()
            .persistent(Codec.DOUBLE)
            .initializer(() -> 0.0)
            .buildAndRegister(BCN.id("efp_own"));

    // ---- per-world (ServerLevel) attachments ----

    /** Global environmental footprint index of the overworld. */
    public static final AttachmentType<Double> EFP = AttachmentRegistry.<Double>builder()
            .persistent(Codec.DOUBLE)
            .initializer(() -> 0.0)
            .buildAndRegister(BCN.id("efp"));

    /** Total MJ produced on this level (statistic). */
    public static final AttachmentType<Long> MJ_GENERATED = AttachmentRegistry.<Long>builder()
            .persistent(Codec.LONG)
            .initializer(() -> 0L)
            .buildAndRegister(BCN.id("mj_generated"));

    /** Active auction house offers. */
    public static final AttachmentType<java.util.List<com.buildcraftneo.economy.AuctionHouse.Offer>> AUCTIONS =
            AttachmentRegistry.<java.util.List<com.buildcraftneo.economy.AuctionHouse.Offer>>builder()
            .persistent(Codec.list(com.buildcraftneo.economy.AuctionHouse.Offer.CODEC))
            .initializer(java.util.List::of)
            .buildAndRegister(BCN.id("auctions"));

    /** Locked inventory slots: slot index (string) -> snapshot stack (ItemLocks analogue). */
    public static final AttachmentType<java.util.Map<String, net.minecraft.world.item.ItemStack>> LOCKED =
            AttachmentRegistry.<java.util.Map<String, net.minecraft.world.item.ItemStack>>builder()
            .persistent(com.mojang.serialization.Codec.unboundedMap(
                    com.mojang.serialization.Codec.STRING,
                    net.minecraft.world.item.ItemStack.CODEC))
            .initializer(java.util.Map::of)
            .buildAndRegister(BCN.id("locked"));

    /** Pending auction payouts: seller name -> MD owed. */
    public static final AttachmentType<java.util.Map<String, Long>> AUCTION_EARNINGS =
            AttachmentRegistry.<java.util.Map<String, Long>>builder()
            .persistent(Codec.unboundedMap(Codec.STRING, Codec.LONG))
            .initializer(java.util.Map::of)
            .buildAndRegister(BCN.id("auction_earnings"));

    public static void register() {
        // static initializers above do the work
    }
}
